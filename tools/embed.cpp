// embed.cpp - build tool: embeds the standard library (lib/*.bfl) into a C++ header.
//
//   embed <output.h> <lib directory>
//
// The header defines kStdLib, an array of {name, text}, which the BFL compiler
// searches for imports and for its built-in prelude.  Generated on every build.
#include <algorithm>
#include <cstdio>
#include <filesystem>
#include <fstream>
#include <sstream>
#include <string>
#include <vector>

int main(int argc, char** argv) {
    if (argc != 3) { fprintf(stderr, "usage: embed <output.h> <lib directory>\n"); return 2; }
    std::vector<std::filesystem::path> files;
    for (const auto& e : std::filesystem::directory_iterator(argv[2]))
        if (e.is_regular_file() && e.path().extension() == ".bfl") files.push_back(e.path());
    std::sort(files.begin(), files.end());
    std::ostringstream o;
    o << "// Generated by tools/embed.cpp from lib/*.bfl on every build; do not edit.\n#pragma once\n\n";
    o << "struct EmbeddedFile { const char* name; const char* text; };\n\nstatic const EmbeddedFile kStdLib[] = {\n";
    for (const auto& p : files) {
        std::ifstream f(p, std::ios::binary);
        std::stringstream ss; ss << f.rdbuf();
        std::string text = ss.str();
        o << "    {\"" << p.filename().string() << "\",\n";
        std::string line;
        size_t n = 0;
        o << "     \"";
        for (char c : text) {
            if (c == '\r') continue;
            if (c == '\n') { o << "\\n\"\n     \""; n = 0; continue; }
            if (c == '\\') o << "\\\\";
            else if (c == '"') o << "\\\"";
            else if ((unsigned char)c < 32 || (unsigned char)c > 126) { char b[8]; snprintf(b, sizeof b, "\\%03o", (unsigned char)c); o << b; }
            else o << c;
            if (++n > 200) { o << "\"\n     \""; n = 0; }
        }
        o << "\"},\n";
    }
    o << "};\n";
    std::string out = o.str();
    // only rewrite when the content changes, so the compiler is not rebuilt needlessly
    std::ifstream old(argv[1], std::ios::binary);
    if (old) { std::stringstream ss; ss << old.rdbuf(); if (ss.str() == out) return 0; }
    std::ofstream w(argv[1], std::ios::binary);
    if (!w) { fprintf(stderr, "embed: cannot write %s\n", argv[1]); return 1; }
    w << out;
    return 0;
}
